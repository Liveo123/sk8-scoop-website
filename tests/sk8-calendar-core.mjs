import assert from 'node:assert/strict';
import fs from 'node:fs';
import core from '../assets/sk8-calendar-core.js';
import { exclusionReason } from '../scripts/event-editorial-exclusions.mjs';

assert.equal(core.validDate('2026-02-29'),false,'reject impossible leap date');
assert.equal(core.validDate('2028-02-29'),true,'accept leap date');
assert.equal(core.anniversaryExclusive('2026-10-08'),'2027-10-08','rolling 12 months');
assert.equal(core.withinHorizon('2027-10-07','2026-10-08'),true);
assert.equal(core.withinHorizon('2027-10-08','2026-10-08'),false);
assert.equal(core.localToday(new Date('2026-10-07T23:30:00Z')),'2026-10-08','UK locale on BST');
assert.equal(core.localToday(new Date('2026-12-31T23:30:00Z')),'2026-12-31','UK locale in GMT');
const recurring={date:'2026-10-10',date_mode:'specific_dates',occurrences:['2026-10-10','2026-10-17',{date:'2026-10-24',status:'cancelled'}]};
assert.deepEqual(core.confirmedDates(recurring),['2026-10-10','2026-10-17']);
assert.equal(core.onDate(recurring,'2026-10-17'),true);
assert.equal(core.onDate(recurring,'2026-10-24'),false);
assert.equal(core.withinRange(recurring,'2026-10-18','2026-10-25'),false);
assert.equal(core.onDate({date:'2026-10-10',end_date:'2026-10-24'},'2026-10-20'),false,'date range must not infer daily performances');
assert.equal(core.withinRange({date:'2026-10-10',end_date:'2026-10-24'},'2026-10-20','2026-10-20'),false);
assert.equal(core.withinRange({date:'2026-10-17',end_date:'2026-10-24'},'2026-10-24','2026-10-25'),false,'weekend view must not invent later theatre sessions');
assert.equal(core.withinRange({date:'2026-10-17',end_date:'2026-10-24'},'2026-10-17','2026-10-18'),true,'confirmed first date remains discoverable');
assert.equal(core.withinRange({date:'2026-10-17',end_date:'2026-10-24'},'2026-10-19','2026-10-25'),false,'week view must not imply daily sessions');
assert.equal(core.withinRange({date:'2026-10-17',end_date:'2026-10-24',date_mode:'daily'},'2026-10-19','2026-10-25'),true,'explicit daily events still match later days');
assert.equal(core.onDate({date:'2026-10-10',end_date:'2026-10-24',date_mode:'daily'},'2026-10-20'),true);
assert.equal(core.isFree({cost:'Free event with normal admission; optional trail £2.50'}),false);
assert.equal(core.isFree({cost:'Free for members · £5 non-members'}),false);
assert.equal(core.isFree({cost:'Free entry'}),true);
assert.equal(core.isFree({cost_type:'free_optional_extras'}),true);
assert.equal(core.isFree({cost_type:'admission_required'}),false);
assert.equal(core.isFree({cost_type:'unknown'}),false);
const events=JSON.parse(fs.readFileSync('data/events.json','utf8'));
const registry=JSON.parse(fs.readFileSync('data/event-sources.json','utf8'));
for(const e of events) assert.ok(!/cheadlemasjid\.org|Cheadle Masjid/i.test([e.source_url,e.booking_url,e.venue].join(' ')),'excluded event resurfaced '+e.id);
for(const s of registry.sources) assert.ok(!/cheadlemasjid\.org|cheadle-masjid/i.test([s.id,s.url].join(' ')),'excluded source resurfaced '+s.id);
assert.match(exclusionReason({source_url:'https://cheadlemasjid.org/events'}),/Excluded organiser/);
assert.match(exclusionReason({venue:'Cheadle Masjid'}),/Excluded organiser/);
assert.equal(exclusionReason({venue:'Cheadle Village Hall',source_url:'https://cheadlevillagehall.co.uk/'}),'');
const gatley = events.find(event => event.id === 'gatley-deckchair-care-welcome-cafe-2026-autumn');
assert.ok(gatley, 'verified Gatley activity included');
assert.equal(gatley.date_mode, 'specific_dates');
assert.equal(core.onDate(gatley, '2026-10-12'), true, 'confirmed Gatley date appears');
assert.equal(core.onDate(gatley, '2026-10-26'), false, 'unconfirmed school-holiday Monday is omitted');
assert.equal(core.onDate(gatley, '2026-11-02'), true, 'confirmed future Gatley date appears');
assert.equal(core.isFree(gatley), true, 'optional donations do not imply mandatory charge');
console.log('Calendar foundation checks passed (dates, recurrence, price, exclusions).');
